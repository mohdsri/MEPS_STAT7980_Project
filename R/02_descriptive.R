  theme_minimal()
ggsave("results/figures/y2_expenditure_distribution.png", p1, width=8, height=5, dpi=300)

p2 <- ggplot(primary, aes(x = factor(high_y1), fill = factor(high_y2), weight = weight)) +
  geom_bar(position = "fill") +
  labs(title="Persistence of high-cost status", x="High cost in Year 1", y="Weighted proportion", fill="High cost Year 2") +
  theme_minimal()
ggsave("results/figures/high_cost_persistence.png", p2, width=7, height=5, dpi=300)
